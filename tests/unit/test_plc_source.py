"""The source files for TIA Portal. Whether they compile can only be seen in TIA Portal."""

import re

import pytest

from highbay_sim import __version__
from highbay_sim.plc.interface import PlcInterface, plc_type_of
from highbay_sim.plc.source import generate_sources
from highbay_sim.signals import SIGNAL_LIST_VERSION, SIGNALS


def sources(crane_count: int = 2, cycle_ms: int = 50) -> dict[str, str]:
    return generate_sources(PlcInterface(crane_count), cycle_ms)


def test_generates_the_three_files() -> None:
    assert set(sources()) == {"HB_Types.udt", "HB_Interface.db", "HB_Control.scl"}


def test_the_user_type_holds_every_signal_with_its_plc_type() -> None:
    text = sources()["HB_Types.udt"]
    assert 'TYPE "HB_CraneSignals"' in text
    for signal in SIGNALS:
        assert re.search(rf"^\s*{signal.name} : {plc_type_of(signal)};$", text, re.MULTILINE)


@pytest.mark.parametrize("crane_count", [1, 2, 3])
def test_the_block_holds_each_crane_and_the_header(crane_count: int) -> None:
    text = sources(crane_count)["HB_Interface.db"]
    assert 'DATA_BLOCK "HB_Interface"' in text
    assert "S7_Optimized_Access := 'TRUE'" in text
    assert text.count('"HB_CraneSignals";') == crane_count
    for aisle in range(1, crane_count + 1):
        assert f'crane_{aisle} : "HB_CraneSignals";' in text
    assert f"crane_{crane_count + 1}" not in text
    assert "interface_version : DInt := 1;" in text
    assert f"signal_list_version : DInt := {SIGNAL_LIST_VERSION};" in text
    assert f"crane_count : DInt := {crane_count};" in text
    for tag in ("plc_heartbeat : DInt;", "reset_request : Bool;", "reset_done : Bool;"):
        assert tag in text


@pytest.mark.parametrize("crane_count", [1, 2, 3])
def test_the_program_calls_the_control_once_per_crane(crane_count: int) -> None:
    text = sources(crane_count)["HB_Control.scl"]
    assert 'FUNCTION_BLOCK "HB_CraneControl"' in text
    assert 'ORGANIZATION_BLOCK "HB_Main"' in text
    assert len(re.findall(r'"HB_Control_\d+"\(crane := ', text)) == crane_count
    for aisle in range(1, crane_count + 1):
        assert f'"HB_Control_{aisle}"(crane := "HB_Interface".crane_{aisle}' in text
        assert f'DATA_BLOCK "HB_Control_{aisle}"' in text


def test_the_main_block_handles_heartbeat_and_reset() -> None:
    text = sources()["HB_Control.scl"]
    assert '"HB_Interface".plc_heartbeat := "HB_Interface".plc_heartbeat + 1;' in text
    assert '"HB_Interface".reset_done := "HB_Interface".reset_request;' in text


@pytest.mark.parametrize(("cycle_ms", "hold", "settle"), [(50, 150, 50), (20, 60, 20)])
def test_the_hold_time_follows_the_cycle_time(cycle_ms: int, hold: int, settle: int) -> None:
    text = sources(cycle_ms=cycle_ms)["HB_Control.scl"]
    assert f"HOLD_TIME : Time := T#{hold}ms;" in text
    assert f"SETTLE_TIME : Time := T#{settle}ms;" in text


def test_the_program_writes_every_signal_only_in_its_own_direction() -> None:
    text = sources()["HB_Control.scl"]
    assigned = set(re.findall(r"#crane\.(\w+) :=", text))
    written_by_plc = {
        signal.name for signal in SIGNALS if signal.direction.startswith("controller_to_")
    }
    assert assigned <= written_by_plc
    assert written_by_plc - assigned == set()


def test_the_program_never_raises_fault_reset() -> None:
    text = sources()["HB_Control.scl"]
    assert "#crane.fault_reset := TRUE" not in text
    assert "#crane.fault_reset := FALSE;" in text


def test_the_program_starts_nothing_new_during_a_fault() -> None:
    text = sources()["HB_Control.scl"]
    assert "#crane.fault_code <> 0" in text


def test_the_program_uses_the_position_tolerance_of_the_built_in_controller() -> None:
    assert "POSITION_TOLERANCE : LReal := 0.001;" in sources()["HB_Control.scl"]


def test_the_software_version_appears_in_a_comment_in_each_file() -> None:
    for text in sources().values():
        assert f"// Generated by highbay-sim {__version__}" in text


def test_generation_is_identical_each_time() -> None:
    assert sources() == sources()


def test_files_hold_no_date_address_or_path() -> None:
    for text in sources().values():
        assert not re.search(r"\b20\d\d-\d\d-\d\d\b", text)
        assert not re.search(r"%[IQMD]", text)
        assert not re.search(r"\bDB\d+\.DB", text)
        assert ":\\" not in text


def test_a_lreal_start_value_is_not_written_for_signals() -> None:
    assert ":= 0.0" not in sources()["HB_Types.udt"]
