"""Generates the source files for TIA Portal, as in contracts/plc-interface.md.

The text is the same for the same interface, cycle time, and software version. Whether it compiles
can only be seen in TIA Portal.
"""

from typing import Final

from highbay_sim import __version__
from highbay_sim.controller import POSITION_TOLERANCE_M
from highbay_sim.plc.interface import INTERFACE_VERSION, PlcInterface, plc_type_of
from highbay_sim.signals import SIGNAL_LIST_VERSION, SIGNALS

HOLD_CYCLES: Final = 3
TYPES_FILE: Final = "HB_Types.udt"
INTERFACE_FILE: Final = "HB_Interface.db"
CONTROL_FILE: Final = "HB_Control.scl"
SOURCE_FILES: Final = (TYPES_FILE, INTERFACE_FILE, CONTROL_FILE)

_COMMENT: Final = f"// Generated by highbay-sim {__version__}. Do not edit: generate it again.\n"

_CONTROL_BLOCK: Final = """FUNCTION_BLOCK "HB_CraneControl"
{ S7_Optimized_Access := 'TRUE' }
VERSION : 0.1
   VAR_INPUT
      reset : Bool;
   END_VAR

   VAR_IN_OUT
      crane : "HB_CraneSignals";
   END_VAR

   VAR
      state : Int;
      phase : Int;
      startMovement : Bool;
      startPick : Bool;
      startSet : Bool;
      waiting : TON_TIME;
      job_id : DInt;
      source_horizontal_m : LReal;
      source_vertical_m : LReal;
      source_side : DInt;
      destination_horizontal_m : LReal;
      destination_vertical_m : LReal;
      destination_side : DInt;
   END_VAR

   VAR CONSTANT
      IDLE : Int := 0;
      TO_SOURCE : Int := 1;
      PICKING : Int := 2;
      TO_DESTINATION : Int := 3;
      SETTING : Int := 4;
      READY : Int := 0;
      SETTLE : Int := 1;
      HOLD_ON : Int := 2;
      HOLD_OFF : Int := 3;
      HOLD_TIME : Time := T#<hold_ms>ms;
      SETTLE_TIME : Time := T#<settle_ms>ms;
      POSITION_TOLERANCE : LReal := <tolerance>;
   END_VAR

BEGIN
   // One transport job per crane: to the source, pick, to the destination, set.
   // The same sequence as the built-in controller. Data settles before a start, a start stays
   // true for the hold time and then false for the hold time, and only then is status judged.
   IF #reset THEN
      #crane.job_done_id := 0;
      #crane.horizontal_target_m := 0.0;
      #crane.vertical_target_m := 0.0;
      #crane.horizontal_start := FALSE;
      #crane.vertical_start := FALSE;
      #crane.side := 0;
      #crane.pick_start := FALSE;
      #crane.set_start := FALSE;
      #crane.fault_reset := FALSE;
      #state := #IDLE;
      #phase := #READY;
      #job_id := 0;
      #waiting(IN := FALSE, PT := #HOLD_TIME);
      RETURN;
   END_IF;

   CASE #phase OF
      #SETTLE:
         #waiting(IN := TRUE, PT := #SETTLE_TIME);
         IF #waiting.Q THEN
            #waiting(IN := FALSE, PT := #SETTLE_TIME);
            #crane.horizontal_start := #startMovement;
            #crane.vertical_start := #startMovement;
            #crane.pick_start := #startPick;
            #crane.set_start := #startSet;
            #phase := #HOLD_ON;
         END_IF;
         RETURN;
      #HOLD_ON:
         #waiting(IN := TRUE, PT := #HOLD_TIME);
         IF #waiting.Q THEN
            #waiting(IN := FALSE, PT := #HOLD_TIME);
            #crane.horizontal_start := FALSE;
            #crane.vertical_start := FALSE;
            #crane.pick_start := FALSE;
            #crane.set_start := FALSE;
            #phase := #HOLD_OFF;
         END_IF;
         RETURN;
      #HOLD_OFF:
         #waiting(IN := TRUE, PT := #HOLD_TIME);
         IF #waiting.Q THEN
            #waiting(IN := FALSE, PT := #HOLD_TIME);
            #phase := #READY;
         END_IF;
         RETURN;
   END_CASE;

   // Nothing new starts during a fault.
   IF #crane.fault_code <> 0 THEN
      RETURN;
   END_IF;

   #startMovement := FALSE;
   #startPick := FALSE;
   #startSet := FALSE;

   CASE #state OF
      #IDLE:
         IF #crane.job_id <> #crane.job_done_id THEN
            // A new job_id means that the job data is complete.
            #job_id := #crane.job_id;
            #source_horizontal_m := #crane.source_horizontal_m;
            #source_vertical_m := #crane.source_vertical_m;
            #source_side := #crane.source_side;
            #destination_horizontal_m := #crane.destination_horizontal_m;
            #destination_vertical_m := #crane.destination_vertical_m;
            #destination_side := #crane.destination_side;
            IF ABS(#crane.horizontal_actual_m - #source_horizontal_m) <= #POSITION_TOLERANCE
               AND ABS(#crane.vertical_actual_m - #source_vertical_m) <= #POSITION_TOLERANCE
            THEN
               #crane.side := #source_side;
               #startPick := TRUE;
               #state := #PICKING;
            ELSE
               #crane.horizontal_target_m := #source_horizontal_m;
               #crane.vertical_target_m := #source_vertical_m;
               #startMovement := TRUE;
               #state := #TO_SOURCE;
            END_IF;
            #phase := #SETTLE;
         END_IF;
      #TO_SOURCE:
         IF #crane.horizontal_in_position AND #crane.vertical_in_position THEN
            #crane.side := #source_side;
            #startPick := TRUE;
            #state := #PICKING;
            #phase := #SETTLE;
         END_IF;
      #PICKING:
         IF #crane.load_present THEN
            IF ABS(#crane.horizontal_actual_m - #destination_horizontal_m) <= #POSITION_TOLERANCE
               AND ABS(#crane.vertical_actual_m - #destination_vertical_m) <= #POSITION_TOLERANCE
            THEN
               #crane.side := #destination_side;
               #startSet := TRUE;
               #state := #SETTING;
            ELSE
               #crane.horizontal_target_m := #destination_horizontal_m;
               #crane.vertical_target_m := #destination_vertical_m;
               #startMovement := TRUE;
               #state := #TO_DESTINATION;
            END_IF;
            #phase := #SETTLE;
         END_IF;
      #TO_DESTINATION:
         IF #crane.horizontal_in_position AND #crane.vertical_in_position THEN
            #crane.side := #destination_side;
            #startSet := TRUE;
            #state := #SETTING;
            #phase := #SETTLE;
         END_IF;
      #SETTING:
         IF NOT #crane.load_present THEN
            #crane.job_done_id := #job_id;
            #state := #IDLE;
         END_IF;
   END_CASE;
END_FUNCTION_BLOCK
"""


def generate_sources(interface: PlcInterface, cycle_ms: int) -> dict[str, str]:
    """The text of each source file, by file name."""
    return {
        TYPES_FILE: _types_text(),
        INTERFACE_FILE: _interface_text(interface),
        CONTROL_FILE: _control_text(interface, cycle_ms),
    }


def _types_text() -> str:
    members = "".join(f"      {s.name} : {plc_type_of(s)};\n" for s in SIGNALS)
    return (
        f'{_COMMENT}TYPE "HB_CraneSignals"\nVERSION : 0.1\n   STRUCT\n{members}'
        "   END_STRUCT;\nEND_TYPE\n"
    )


def _interface_text(interface: PlcInterface) -> str:
    cranes = "".join(f'      crane_{a} : "HB_CraneSignals";\n' for a in interface.aisles)
    return (
        f'{_COMMENT}DATA_BLOCK "HB_Interface"\n'
        "{ S7_Optimized_Access := 'TRUE' }\n"
        "VERSION : 0.1\n"
        "NON_RETAIN\n"
        "   VAR\n"
        f"      interface_version : DInt := {INTERFACE_VERSION};\n"
        f"      signal_list_version : DInt := {SIGNAL_LIST_VERSION};\n"
        f"      crane_count : DInt := {interface.crane_count};\n"
        "      plc_heartbeat : DInt;\n"
        "      reset_request : Bool;\n"
        "      reset_done : Bool;\n"
        f"{cranes}"
        "   END_VAR\n"
        "BEGIN\n"
        "END_DATA_BLOCK\n"
    )


def _control_text(interface: PlcInterface, cycle_ms: int) -> str:
    block = (
        _CONTROL_BLOCK.replace("<hold_ms>", str(HOLD_CYCLES * cycle_ms))
        .replace("<settle_ms>", str(cycle_ms))
        .replace("<tolerance>", str(POSITION_TOLERANCE_M))
    )
    instances = "".join(
        f'DATA_BLOCK "HB_Control_{a}"\n'
        "{ S7_Optimized_Access := 'TRUE' }\n"
        "VERSION : 0.1\n"
        "NON_RETAIN\n"
        '"HB_CraneControl"\n'
        "BEGIN\n"
        "END_DATA_BLOCK\n\n"
        for a in interface.aisles
    )
    calls = "".join(
        f'   "HB_Control_{a}"(crane := "HB_Interface".crane_{a}, '
        'reset := "HB_Interface".reset_request);\n'
        for a in interface.aisles
    )
    return (
        f"{_COMMENT}{block}\n{instances}"
        'ORGANIZATION_BLOCK "HB_Main"\n'
        "{ S7_Optimized_Access := 'TRUE' }\n"
        "VERSION : 0.1\n"
        "BEGIN\n"
        '   "HB_Interface".plc_heartbeat := "HB_Interface".plc_heartbeat + 1;\n'
        f"{calls}"
        '   "HB_Interface".reset_done := "HB_Interface".reset_request;\n'
        "END_ORGANIZATION_BLOCK\n"
    )
